-- Canonical AUDIT_USER schema contract.
-- Review this file and obtain explicit approval before any live execution.
-- Existing incompatible objects fail closed during the metadata assertions.

DECLARE
    PROCEDURE create_table_if_missing(p_sql CLOB) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -955 THEN
                RAISE;
            END IF;
    END;

    PROCEDURE create_index_if_missing(p_sql CLOB) IS
    BEGIN
        EXECUTE IMMEDIATE p_sql;
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE NOT IN (-955, -1408) THEN
                RAISE;
            END IF;
    END;

    PROCEDURE assert_column(
        p_table       VARCHAR2,
        p_column      VARCHAR2,
        p_data_type   VARCHAR2,
        p_min_length  NUMBER DEFAULT NULL
    ) IS
        column_count NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO column_count
          FROM ALL_TAB_COLUMNS
         WHERE OWNER = 'AUDIT_USER'
           AND TABLE_NAME = p_table
           AND COLUMN_NAME = p_column
           AND DATA_TYPE = p_data_type
           AND (p_min_length IS NULL OR DATA_LENGTH >= p_min_length);

        IF column_count != 1 THEN
            RAISE_APPLICATION_ERROR(-20081, 'AUDIT_SCHEMA_CONTRACT_MISMATCH');
        END IF;
    END;
BEGIN
    create_table_if_missing(q'~
        CREATE TABLE AUDIT_USER.ALERT_LOG (
            ALERT_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            ALERT_TYPE      VARCHAR2(50) NOT NULL,
            SOURCE          VARCHAR2(200),
            MESSAGE         VARCHAR2(2000) NOT NULL,
            TABLE_OWNER     VARCHAR2(128),
            TABLE_NAME      VARCHAR2(128),
            DETAILS         CLOB,
            SEVERITY        VARCHAR2(20) DEFAULT 'WARNING',
            ACKNOWLEDGED    NUMBER(1) DEFAULT 0,
            ACKNOWLEDGED_AT TIMESTAMP,
            CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
        )
    ~');
    assert_column('ALERT_LOG', 'ALERT_ID', 'NUMBER');
    assert_column('ALERT_LOG', 'ALERT_TYPE', 'VARCHAR2', 50);
    assert_column('ALERT_LOG', 'CREATED_AT', 'TIMESTAMP(6)');

    create_table_if_missing(q'~
        CREATE TABLE AUDIT_USER.MAPPING_LOG (
            LOG_ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            BATCH_ID        VARCHAR2(64) NOT NULL,
            OPERATION       VARCHAR2(50) NOT NULL,
            OBJECT_OWNER    VARCHAR2(128),
            OBJECT_NAME     VARCHAR2(128) NOT NULL,
            DDL_TEXT        CLOB,
            STATUS          VARCHAR2(20) DEFAULT 'SUCCESS',
            ERROR_MESSAGE   VARCHAR2(2000),
            CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
        )
    ~');
    assert_column('MAPPING_LOG', 'LOG_ID', 'NUMBER');
    assert_column('MAPPING_LOG', 'BATCH_ID', 'VARCHAR2', 64);
    assert_column('MAPPING_LOG', 'CREATED_AT', 'TIMESTAMP(6)');

    create_table_if_missing(q'~
        CREATE TABLE AUDIT_USER.DATA_LINEAGE (
            LINEAGE_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            MAPPING_NAME    VARCHAR2(256) NOT NULL,
            SOURCE_OWNER    VARCHAR2(128),
            SOURCE_TABLE    VARCHAR2(128) NOT NULL,
            SOURCE_COLUMN   VARCHAR2(128),
            TARGET_OWNER    VARCHAR2(128),
            TARGET_TABLE    VARCHAR2(128) NOT NULL,
            TARGET_COLUMN   VARCHAR2(128),
            EXPRESSION      VARCHAR2(4000),
            UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
        )
    ~');
    assert_column('DATA_LINEAGE', 'LINEAGE_ID', 'NUMBER');
    assert_column('DATA_LINEAGE', 'MAPPING_NAME', 'VARCHAR2', 256);
    assert_column('DATA_LINEAGE', 'UPDATED_AT', 'TIMESTAMP(6)');

    create_table_if_missing(q'~
        CREATE TABLE AUDIT_USER.MAPPING_SNAPSHOT (
            SNAP_ID       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            MAPPING_NAME  VARCHAR2(256) NOT NULL,
            SNAP_DATE     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            SNAP_LABEL    VARCHAR2(100),
            SNAP_HASH     VARCHAR2(64),
            SNAP_JSON     CLOB
        )
    ~');
    assert_column('MAPPING_SNAPSHOT', 'SNAP_ID', 'NUMBER');
    assert_column('MAPPING_SNAPSHOT', 'MAPPING_NAME', 'VARCHAR2', 256);
    assert_column('MAPPING_SNAPSHOT', 'SNAP_DATE', 'TIMESTAMP(6)');

    create_table_if_missing(q'~
        CREATE TABLE AUDIT_USER.MAPPING_RUN_STATE (
            RUN_ID          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            BATCH_ID        VARCHAR2(64) NOT NULL,
            THREAD_ID       VARCHAR2(128),
            MAPPING_NAME    VARCHAR2(256),
            CURRENT_STEP    VARCHAR2(100),
            OVERALL_STATUS  VARCHAR2(30),
            COMPLETED_STEPS VARCHAR2(2000),
            ERROR_MESSAGE   VARCHAR2(2000),
            STATE_JSON      CLOB,
            CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            UPDATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
        )
    ~');
    assert_column('MAPPING_RUN_STATE', 'RUN_ID', 'NUMBER');
    assert_column('MAPPING_RUN_STATE', 'BATCH_ID', 'VARCHAR2', 64);
    assert_column('MAPPING_RUN_STATE', 'STATE_JSON', 'CLOB');
    assert_column('MAPPING_RUN_STATE', 'UPDATED_AT', 'TIMESTAMP(6)');

    create_index_if_missing('CREATE INDEX AUDIT_USER.IDX_ALERT_LOG_ACK ON AUDIT_USER.ALERT_LOG (ACKNOWLEDGED, CREATED_AT DESC)');
    create_index_if_missing('CREATE INDEX AUDIT_USER.IDX_ALERT_LOG_TYPE ON AUDIT_USER.ALERT_LOG (ALERT_TYPE, CREATED_AT DESC)');
    create_index_if_missing('CREATE INDEX AUDIT_USER.IDX_MAPPING_LOG_BATCH ON AUDIT_USER.MAPPING_LOG (BATCH_ID, CREATED_AT)');
    create_index_if_missing('CREATE INDEX AUDIT_USER.IDX_LINEAGE_SRC ON AUDIT_USER.DATA_LINEAGE (SOURCE_OWNER, SOURCE_TABLE)');
    create_index_if_missing('CREATE INDEX AUDIT_USER.IDX_LINEAGE_TGT ON AUDIT_USER.DATA_LINEAGE (TARGET_OWNER, TARGET_TABLE)');
    create_index_if_missing('CREATE INDEX AUDIT_USER.IDX_LINEAGE_MAP ON AUDIT_USER.DATA_LINEAGE (MAPPING_NAME)');
    create_index_if_missing('CREATE INDEX AUDIT_USER.IDX_SNAPSHOT_MAP ON AUDIT_USER.MAPPING_SNAPSHOT (MAPPING_NAME, SNAP_DATE DESC)');
    create_index_if_missing('CREATE UNIQUE INDEX AUDIT_USER.UQ_MAPPING_RUN_STATE_BATCH ON AUDIT_USER.MAPPING_RUN_STATE (BATCH_ID)');
    create_index_if_missing('CREATE INDEX AUDIT_USER.IX_MAPPING_RUN_STATE_NAME ON AUDIT_USER.MAPPING_RUN_STATE (MAPPING_NAME)');
    create_index_if_missing('CREATE INDEX AUDIT_USER.IX_MAPPING_RUN_STATE_UPDATED ON AUDIT_USER.MAPPING_RUN_STATE (UPDATED_AT)');

    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON AUDIT_USER.ALERT_LOG TO APP_USER';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON AUDIT_USER.MAPPING_LOG TO APP_USER';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, DELETE ON AUDIT_USER.DATA_LINEAGE TO APP_USER';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT ON AUDIT_USER.MAPPING_SNAPSHOT TO APP_USER';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON AUDIT_USER.MAPPING_RUN_STATE TO APP_USER';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT ON AUDIT_USER.DATA_LINEAGE TO ODI_EXEC';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON AUDIT_USER.ALERT_LOG TO DWH';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON AUDIT_USER.MAPPING_LOG TO DWH';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, DELETE ON AUDIT_USER.DATA_LINEAGE TO DWH';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT ON AUDIT_USER.MAPPING_SNAPSHOT TO DWH';
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON AUDIT_USER.MAPPING_RUN_STATE TO DWH';

    DBMS_OUTPUT.PUT_LINE('AUDIT_SCHEMA_CONTRACT_READY');
END;
